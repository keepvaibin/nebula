"""The license texts of the Rust crates statically linked into one package's binary.

    python tools/rust_licenses.py <package> <target triple> <output> "<binary description>"

Walks the package's normal (not build or dev) dependencies for that target from `cargo metadata`, leaving out
procedural macros (they run in the compiler), and writes each crate's name, version, license expression,
repository and license files (LICENSE*, COPYING*, NOTICE*, UNLICENSE*). A crate that ships no license file is
listed with its declared expression. The two lists in docs/licenses:

    python tools/rust_licenses.py nebula-import x86_64-pc-windows-msvc docs/licenses/rust-dependencies.txt
        "nebula-import.exe (Windows Setup's importer)"
    python tools/rust_licenses.py nebula-import aarch64-linux-android docs/licenses/rust-dependencies-android.txt
        "libnebula_import.so (the Android app's setup)"
"""
import json
import pathlib
import subprocess
import sys

package, target, output, binary = sys.argv[1:5]
root = pathlib.Path(__file__).resolve().parent.parent
metadata = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--format-version", "1", "--filter-platform", target, "--locked"], cwd=root))
packages = {p["id"]: p for p in metadata["packages"]}
nodes = {n["id"]: n for n in metadata["resolve"]["nodes"]}
start = next(p["id"] for p in metadata["packages"] if p["name"] == package and p["source"] is None)

linked = set()
queue = [start]
while queue:
    current = queue.pop()
    for dep in nodes[current]["deps"]:
        if not any(kind["kind"] is None for kind in dep["dep_kinds"]):
            continue  # build scripts and tests only
        if any("proc-macro" in t["kind"] for t in packages[dep["pkg"]]["targets"]):
            continue  # runs in the compiler, not linked
        if dep["pkg"] not in linked:
            linked.add(dep["pkg"])
            queue.append(dep["pkg"])

local = {p["id"] for p in metadata["packages"] if p["source"] is None}
crates = sorted((packages[i] for i in linked if i not in local), key=lambda p: (p["name"], p["version"]))
prefixes = ("license", "copying", "notice", "unlicense")
lines = [f"Licenses of the Rust crates statically linked into {binary}",
         "(generated by tools/rust_licenses.py from Cargo.lock and the crate sources; C libraries vendored by",
         " -sys crates are included in those crates' files)", ""]
for crate in crates:
    directory = pathlib.Path(crate["manifest_path"]).parent
    lines.append("=" * 78)
    lines.append(f"{crate['name']} {crate['version']} — {crate.get('license') or 'see files'}")
    if crate.get("repository"):
        lines.append(crate["repository"])
    files = sorted(f for f in directory.iterdir() if f.is_file() and f.name.lower().startswith(prefixes))
    if not files:
        lines.append(f"(no license file in the crate; it declares {crate.get('license')})")
    for file in files:
        lines.append(f"------------------------------ {file.name}")
        lines.append(file.read_text(encoding="utf-8", errors="replace").rstrip())
    lines.append("")
pathlib.Path(output).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"{len(crates)} crates -> {output}")
