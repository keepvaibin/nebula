"""Writes runtime/src/render/materials/shade_dfg.hlsli: the split-sum environment terms of the GGX lobe.

What a GGX surface (height-correlated Smith masking, Schlick's Fresnel) reflects of light arriving evenly over its
lobe is F0 * A + B (Karis 2013, "Real Shading in Unreal Engine 4"). A and B depend on n.v and the roughness. Table:
32 x 32 nodes, n.v = 0.005 + 0.995 (i / 31)^2 across (the terms change fastest at a glance, so the nodes crowd there) and the
perceptual roughness r = j / 31 down (GGX alpha = r^2). The shader looks up n.v of at least kShadeNvLeast
(0.005: a look within 0.3 degrees of the surface, where masking falls off a cliff no table of this size follows). There
the bilinear interpolation stays within 0.015 of the integral, and within 0.005 where n.v is over 0.05; this script
checks that at 4,000 random points. Row r = 0 is the mirror exactly: A = 1 - (1 - n.v)^5, B = (1 - n.v)^5.

    python tools/dev/make_dfg_table.py            # writes the header
    python tools/dev/make_dfg_table.py --check    # exit 1 when the header differs from what this writes
"""

import argparse
import pathlib
import sys

import numpy as np

N = 32
SAMPLES = 8192
NV_LEAST = 0.005  # the shader's kShadeNvLeast
OUT = pathlib.Path(__file__).resolve().parents[2] / "runtime" / "src" / "render" / "materials" / "shade_dfg.hlsli"


def hammersley(count):
    i = np.arange(count, dtype=np.uint32)
    bits = i.copy()
    bits = ((bits << 16) | (bits >> 16)) & 0xFFFFFFFF
    bits = ((bits & 0x55555555) << 1) | ((bits & 0xAAAAAAAA) >> 1)
    bits = ((bits & 0x33333333) << 2) | ((bits & 0xCCCCCCCC) >> 2)
    bits = ((bits & 0x0F0F0F0F) << 4) | ((bits & 0xF0F0F0F0) >> 4)
    bits = ((bits & 0x00FF00FF) << 8) | ((bits & 0xFF00FF00) >> 8)
    return (i + 0.5) / count, bits.astype(np.float64) / 2.0**32


def terms(nv, rough):
    """A, B for arrays nv, rough of one shape."""
    nv = np.maximum(nv, 1e-4)
    alpha = rough * rough
    a2 = alpha * alpha
    u1, u2 = hammersley(SAMPLES)
    # GGX half vectors about n = z, sampled by D(h) (h.n): cos^2 = (1 - u) / (1 + (a2 - 1) u).
    cos_h = np.sqrt((1.0 - u1[None, :]) / (1.0 + (a2[:, None] - 1.0) * u1[None, :]))
    sin_h = np.sqrt(np.maximum(1.0 - cos_h * cos_h, 0.0))
    phi = 2.0 * np.pi * u2[None, :]
    hx, hy, hz = sin_h * np.cos(phi), sin_h * np.sin(phi), cos_h
    vx, vz = np.sqrt(1.0 - nv * nv)[:, None], nv[:, None]
    vh = vx * hx + vz * hz
    lz = 2.0 * vh * hz - vz
    ok = (lz > 0.0) & (vh > 0.0)
    nl = np.where(ok, lz, 1.0)
    # Height-correlated Smith visibility G / (4 n.l n.v) (Heitz 2014).
    lam_v = nl * np.sqrt(vz * vz * (1.0 - a2[:, None]) + a2[:, None])
    lam_l = vz * np.sqrt(nl * nl * (1.0 - a2[:, None]) + a2[:, None])
    vis = 0.5 / (lam_v + lam_l)
    # Estimator of the BRDF times n.l over the pdf D (h.n) / (4 v.h), Fresnel left out.
    w = np.where(ok, vis * 4.0 * nl * vh / hz, 0.0)
    fc = (1.0 - np.clip(vh, 0.0, 1.0)) ** 5
    a = np.mean(w * (1.0 - fc), axis=1)
    b = np.mean(w * fc, axis=1)
    mirror = rough <= 0.0
    p = (1.0 - nv) ** 5
    a = np.where(mirror, 1.0 - p, a)
    b = np.where(mirror, p, b)
    return a, b


def table(n):
    nv = np.tile(NV_LEAST + (1.0 - NV_LEAST) * (np.arange(n) / (n - 1)) ** 2, n)
    rough = np.repeat(np.arange(n) / (n - 1), n)
    a, b = terms(nv, rough)
    return a.reshape(n, n), b.reshape(n, n)


def bilinear(t, nv, rough):
    n = t.shape[0]
    x, y = np.sqrt((nv - NV_LEAST) / (1.0 - NV_LEAST)) * (n - 1), rough * (n - 1)
    x0, y0 = np.minimum(np.floor(x).astype(int), n - 2), np.minimum(np.floor(y).astype(int), n - 2)
    fx, fy = x - x0, y - y0
    top = t[y0, x0] * (1 - fx) + t[y0, x0 + 1] * fx
    bottom = t[y0 + 1, x0] * (1 - fx) + t[y0 + 1, x0 + 1] * fx
    return top * (1 - fy) + bottom * fy


def render(a, b):
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-only",
        "// Generated by tools/dev/make_dfg_table.py; do not edit. The split-sum environment terms of the GGX lobe",
        "// (height-correlated Smith, Schlick's Fresnel): what the surface reflects of even light over its lobe is",
        "// F0 * A + B. 32 x 32 nodes: n.v = 0.005 + 0.995 (i / 31)^2 across, perceptual roughness j / 31 down;",
        "// float2(A, B).",
        "#ifndef NEBULA_SHADE_DFG_HLSLI",
        "#define NEBULA_SHADE_DFG_HLSLI",
        "",
        f"static const float2 kShadeDfg[{N * N}] = {{",
    ]
    for j in range(N):
        row = ", ".join(f"float2({a[j, i]:.5f}f, {b[j, i]:.5f}f)" for i in range(N))
        lines.append(f"    {row},")
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    a, b = table(N)
    rng = np.random.default_rng(1)
    nv = np.maximum(rng.uniform(0.0, 1.0, 4000) ** 2, NV_LEAST)
    rough = rng.uniform(0.0, 1.0, 4000)
    exact_a, exact_b = terms(nv, rough)
    err = max(np.max(np.abs(bilinear(a, nv, rough) - exact_a)), np.max(np.abs(bilinear(b, nv, rough) - exact_b)))
    text = render(a, b)
    if args.check:
        same = OUT.exists() and OUT.read_text(encoding="utf-8").replace("\r\n", "\n") == text
        print(f"interpolation error {err:.4f}; header {'matches' if same else 'differs'}")
        return 0 if same and err < 0.015 else 1
    OUT.write_bytes(text.replace("\n", "\r\n").encode("utf-8"))
    print(f"wrote {OUT} (interpolation error {err:.4f})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
