"""The tracer's shaders, compiled at build into one header. compile_rt_shaders.py dxil|spirv DXC OUT.h

runtime/src/render/rt/shaders.tsv lists them (name, file, profile, entry) in RtShader's order (rt_shaders.h). One HLSL
source serves every back end: dxc writes DXIL for Direct3D 12 and SPIR-V for Vulkan (a dxc built with SPIR-V; the Windows
SDK's has none). The header holds one byte array per shader and kRtShaders, the table rt_shaders.cpp returns."""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCES = os.path.join(ROOT, "runtime", "src", "render", "rt")


def main():
    backend, dxc, out = sys.argv[1], sys.argv[2], sys.argv[3]
    work = os.path.splitext(out)[0] + "_objects"
    os.makedirs(work, exist_ok=True)
    rows = []
    with open(os.path.join(SOURCES, "shaders.tsv"), encoding="utf-8") as f:
        for line in list(f)[1:]:
            parts = line.rstrip("\r\n").split("\t")
            if len(parts) == 4:
                rows.append(parts)
    lines = ["// Generated by tools/dev/compile_rt_shaders.py (" + backend + "); do not edit.", "#include <cstddef>", ""]
    for name, file, profile, entry in rows:
        target = os.path.join(work, name + (".dxil" if backend == "dxil" else ".spv"))
        command = [dxc, "-nologo", "-T", profile, "-E", entry, "-O3", "-I", SOURCES,
                   "-I", os.path.join(ROOT, "runtime", "src", "render", "materials"), os.path.join(SOURCES, file), "-Fo", target]
        if backend == "spirv":
            # Vulkan 1.2 (SPIR-V 1.5); registers keep their numbers within a kind: t at 0, s at 100, u at 200, b at 300 of
            # the set their space names.
            command += ["-spirv", "-fspv-target-env=vulkan1.2", "-fvk-t-shift", "0", "all", "-fvk-s-shift", "100", "all",
                        "-fvk-u-shift", "200", "all", "-fvk-b-shift", "300", "all", "-DNEBULA_VULKAN=1"]
        done = subprocess.run(command, capture_output=True, text=True)
        if done.returncode != 0 or not os.path.exists(target):
            sys.stderr.write("%s (%s): %s%s\n" % (file, backend, done.stdout, done.stderr))
            return 1
        with open(target, "rb") as f:
            data = f.read()
        lines.append("alignas(4) static const unsigned char g_rt_%s[] = {" % name)
        for at in range(0, len(data), 24):
            lines.append("    " + ",".join(str(b) for b in data[at:at + 24]) + ",")
        lines.append("};")
    lines.append("")
    lines.append("static const struct { const unsigned char* data; std::size_t size; } kRtShaders[] = {")
    for name, _, _, _ in rows:
        lines.append("    {g_rt_%s, sizeof(g_rt_%s)}," % (name, name))
    lines.append("};")
    text = "\n".join(lines) + "\n"
    old = None
    if os.path.exists(out):
        with open(out, encoding="utf-8") as f:
            old = f.read()
    if old != text:
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    return 0


sys.exit(main())
