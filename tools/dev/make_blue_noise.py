"""The tracer's blue noise: runtime/src/render/rt/rt_blue_noise.inc, a 128 x 128 texture of four channels of eight
bits, each channel its own void-and-cluster run (Ulichney 1993: Gaussian energy, sigma 1.9, on a torus) with its own
fixed seed: the same file every time. The file is committed; this runs at build only where it is missing.
Usage: python -I tools/dev/make_blue_noise.py [OUT]"""
import os
import sys

import numpy as np

SIZE = 128
SIGMA = 1.9
SEEDS = (0x6E656275, 0x6C61626E, 0x6F697365, 0x72617973)  # one a channel
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "runtime", "src", "render", "rt", "rt_blue_noise.inc")


def kernel():
    """The energy one point gives every pixel of the torus, centred on (0, 0)."""
    d = np.minimum(np.arange(SIZE), SIZE - np.arange(SIZE)).astype(np.float64)
    return np.exp(-(d[:, None] ** 2 + d[None, :] ** 2) / (2.0 * SIGMA * SIGMA))


def energy_of(pattern, k):
    return np.real(np.fft.ifft2(np.fft.fft2(pattern) * np.fft.fft2(k)))


def at(index):
    return divmod(int(index), SIZE)


def rank_channel(seed, k):
    """Void and cluster: the order in which every pixel joins, as ranks 0 .. SIZE*SIZE-1."""
    rng = np.random.default_rng(seed)
    count = SIZE * SIZE
    ones = count // 10
    pattern = np.zeros((SIZE, SIZE))
    pattern.flat[rng.choice(count, ones, replace=False)] = 1.0
    energy = energy_of(pattern, k)

    def add(e, y, x, sign):
        e += sign * np.roll(np.roll(k, y, axis=0), x, axis=1)

    # The initial pattern made even: move the tightest cluster to the largest void until they are the same pixel.
    while True:
        cluster = np.argmax(np.where(pattern > 0.5, energy, -np.inf))
        y, x = at(cluster)
        pattern[y, x] = 0.0
        add(energy, y, x, -1.0)
        void = np.argmax(np.where(pattern < 0.5, -energy, -np.inf))
        vy, vx = at(void)
        pattern[vy, vx] = 1.0
        add(energy, vy, vx, 1.0)
        if void == cluster:
            break
    ranks = np.zeros((SIZE, SIZE), dtype=np.int64)
    # Phase 1: the initial points, ranked by taking the tightest cluster away.
    work, work_energy = pattern.copy(), energy.copy()
    for rank in range(ones - 1, -1, -1):
        cluster = np.argmax(np.where(work > 0.5, work_energy, -np.inf))
        y, x = at(cluster)
        work[y, x] = 0.0
        add(work_energy, y, x, -1.0)
        ranks[y, x] = rank
    # Phase 2: up to half full, the largest void joins next.
    for rank in range(ones, count // 2):
        void = np.argmax(np.where(pattern < 0.5, -energy, -np.inf))
        y, x = at(void)
        pattern[y, x] = 1.0
        add(energy, y, x, 1.0)
        ranks[y, x] = rank
    # Phase 3: the rest, by the tightest cluster of what is still out (the energy of the pixels left out).
    left = 1.0 - pattern
    left_energy = energy_of(left, k)
    for rank in range(count // 2, count):
        cluster = np.argmax(np.where(left > 0.5, left_energy, -np.inf))
        y, x = at(cluster)
        left[y, x] = 0.0
        add(left_energy, y, x, -1.0)
        ranks[y, x] = rank
    return ranks


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else OUT
    k = kernel()
    channels = [(rank_channel(seed, k) * 256 // (SIZE * SIZE)).astype(np.uint8) for seed in SEEDS]
    texels = np.stack(channels, axis=-1).reshape(-1)
    lines = ["// Generated by tools/dev/make_blue_noise.py; do not edit. 128 x 128 texels, RGBA, one byte a channel:",
             "// four independent void-and-cluster runs (sigma 1.9, toroidal), each value's rank among 16384 as 0-255.",
             "inline constexpr unsigned kRtBlueNoiseSize = 128u;",
             "alignas(4) inline constexpr unsigned char kRtBlueNoise[128u * 128u * 4u] = {"]
    for start in range(0, texels.size, 32):
        lines.append("    " + ",".join(str(int(v)) for v in texels[start:start + 32]) + ",")
    lines.append("};")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
