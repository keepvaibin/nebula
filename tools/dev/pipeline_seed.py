#!/usr/bin/env python3
"""pipeline_seed.py OUT.inc FILE...: the pipeline seed table from GALAXY_PIPELINE_SEED_OUT files, sorted and unique."""
import sys

rows = set()
for name in sys.argv[2:]:
    for line in open(name, encoding='ascii'):
        parts = line.split()
        if len(parts) == 6:
            rows.add(tuple(int(p) for p in parts))
with open(sys.argv[1], 'w', newline='\n') as out:
    out.write('// Generated by tools/dev/pipeline_seed.py from tours.\n')
    for r in sorted(rows):
        out.write('    {%du, %du, %du, %du, %du, %du},\n' % r)
print(len(rows), 'pipelines')
