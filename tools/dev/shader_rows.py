"""Writes native/include/nebula_shader_rows.h: how many rows of constants each written shader declares (HLSL packing)."""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
API = os.path.join(ROOT, "native", "include", "nebula_game_api.h")
MATERIALS = os.path.join(ROOT, "runtime", "src", "render", "materials")
OUT = os.path.join(ROOT, "native", "include", "nebula_shader_rows.h")
SIZES = {"float": 1, "uint": 1, "int": 1, "float2": 2, "float3": 3, "float4": 4, "uint2": 2, "uint3": 3, "uint4": 4, "int2": 2, "int3": 3, "int4": 4}


def rows_of(text, name):
    m = re.search(r"struct\s+MaterialConstants\s*\{(.*?)\};", text, re.S)
    if not m:
        return 0
    at = 0
    body = re.sub(r"//[^\n]*", "", m.group(1))
    for field in body.split(";"):
        field = field.strip()
        if not field:
            continue
        g = re.fullmatch(r"(?:row_major\s+)?(\w+)\s+\w+(?:\s*\[\s*(\w+)\s*\])?", field)
        if not g:
            sys.exit("%s: cannot read %r" % (name, field))
        kind, count = g.group(1), g.group(2)
        if kind in ("float3x4", "float4x4", "float4x3"):
            size = 16 * (3 if kind != "float4x4" else 4)
            at = (at + 15) // 16 * 16
            at += size * (int(count) if count else 1)
            continue
        if kind not in SIZES:
            sys.exit("%s: unknown type %s" % (name, kind))
        size = SIZES[kind] * 4
        if count:
            at = (at + 15) // 16 * 16
            at += 16 * int(count)
        else:
            if at // 16 != (at + size - 1) // 16:
                at = (at + 15) // 16 * 16
            at += size
    return (at + 15) // 16


api = open(API, encoding="utf-8").read()
ids = re.findall(r"NEBULA_SHADER_(\w+)\s*=\s*(\d+)", api)
table = {}
for name, value in ids:
    path = os.path.join(MATERIALS, name.lower() + ".hlsl")
    if not os.path.exists(path):
        if name == "NONE":
            table[int(value)] = (name, 0)
        continue
    table[int(value)] = (name, rows_of(open(path, encoding="utf-8").read(), name))
lines = ["#pragma once", "", "/* Generated by tools/dev/shader_rows.py: rows of constants each written shader declares. */", "", "static const unsigned char nebula_shader_rows[] = {"]
for value in sorted(table):
    lines.append("    %d, /* %s */" % (table[value][1], table[value][0]))
lines += ["};", ""]
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print(sorted((v[1], v[0]) for v in table.values())[-6:], len(table), sorted(table)[:3], sorted(table)[-1])
