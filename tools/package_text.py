"""package_text.py: the packages' own words (plan 2.9), from localization/PackageText.tsv, in every language the game
ships (the columns of NebulaText.tsv). These are the texts the system shows for Nebula outside the game: macOS's and
iOS's questions before a mod first reaches the microphone, the camera or the local network, and the name of a .luma
in a file manager. A package cannot change them after release, so they ship in every language now.

  package_text.py apple <Resources folder>   writes <lang>.lproj/InfoPlist.strings for each language (build_macos.sh)
  package_text.py linux [--check]            writes (or checks) platform/linux/dev.nebula.galaxy.xml, the shared MIME
                                             type of *.luma with its name in each language
"""
import pathlib
import sys
from xml.sax.saxutils import escape

ROOT = pathlib.Path(__file__).resolve().parent.parent
TSV = ROOT / "localization" / "PackageText.tsv"
MIME = ROOT / "platform" / "linux" / "dev.nebula.galaxy.xml"

# Each column's Apple localization and freedesktop xml:lang ("" is the file's default, English).
LANGS = {
    "UsEnglish": ("en", ""),
    "EuEnglish": ("en-GB", "en_GB"),
    "UsFrench": ("fr-CA", "fr_CA"),
    "EuFrench": ("fr", "fr"),
    "UsSpanish": ("es-419", "es_MX"),
    "EuSpanish": ("es", "es"),
    "EuGerman": ("de", "de"),
    "EuItalian": ("it", "it"),
    "EuDutch": ("nl", "nl"),
    "UsPortuguese": ("pt-BR", "pt_BR"),
    "JpJapanese": ("ja", "ja"),
    "KrKorean": ("ko", "ko"),
    "CnSimpChinese": ("zh-Hans", "zh_CN"),
    "TwTradChinese": ("zh-Hant", "zh_TW"),
}
# Info.plist keys and the row each takes. "Nebula mod" is the document type's name (CFBundleTypeName and
# UTTypeDescription in Info.macos.plist.in), localized by its English text as the key.
APPLE = [
    ("NSMicrophoneUsageDescription", "Package.MicrophoneUse"),
    ("NSCameraUsageDescription", "Package.CameraUse"),
    ("NSLocalNetworkUsageDescription", "Package.LocalNetworkUse"),
    ("Nebula mod", "Package.ModType"),
]


def read():
    lines = TSV.read_text(encoding="utf-8").splitlines()
    head = lines[0].split("\t")
    if head[0] != "id" or sorted(head[1:]) != sorted(LANGS):
        sys.exit("%s: the columns are not id and the 14 languages" % TSV)
    rows = {}
    for n, line in enumerate(lines[1:], 2):
        cells = line.split("\t")
        if len(cells) != len(head) or any(not c.strip() for c in cells):
            sys.exit("%s:%d: a row needs every language" % (TSV, n))
        rows[cells[0]] = dict(zip(head[1:], cells[1:]))
    return rows


def strings_text(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def apple(resources):
    rows = read()
    for column, (lproj, _) in LANGS.items():
        folder = pathlib.Path(resources) / (lproj + ".lproj")
        folder.mkdir(parents=True, exist_ok=True)
        text = "".join("%s = %s;\n" % (strings_text(key), strings_text(rows[row][column])) for key, row in APPLE)
        (folder / "InfoPlist.strings").write_text(text, encoding="utf-16")  # UTF-16 with its mark, as CFBundle reads
    print("InfoPlist.strings in %d languages" % len(LANGS))


def mime_xml():
    rows = read()
    names = []
    for column, (_, lang) in LANGS.items():
        value = escape(rows["Package.ModType"][column])
        names.append('    <comment%s>%s</comment>' % (' xml:lang="%s"' % lang if lang else "", value))
    return ("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"
            "<!-- Generated by tools/package_text.py from localization/PackageText.tsv: edit those, not this. The\n"
            "     shared MIME type of a .luma (plan 2.9); the desktop entry dev.nebula.galaxy.desktop opens it. -->\n"
            "<mime-info xmlns=\"http://www.freedesktop.org/standards/shared-mime-info\">\n"
            "  <mime-type type=\"application/x-nebula-luma\">\n"
            + "\n".join(names) + "\n"
            "    <sub-class-of type=\"application/zip\"/>\n"
            "    <glob pattern=\"*.luma\"/>\n"
            "  </mime-type>\n"
            "</mime-info>\n")


def linux(check):
    text = mime_xml()
    if check:
        if not MIME.exists() or MIME.read_text(encoding="utf-8") != text:
            sys.exit("%s is not what PackageText.tsv makes: run tools/package_text.py linux" % MIME)
        print("%s matches" % MIME.name)
        return
    MIME.parent.mkdir(parents=True, exist_ok=True)
    MIME.write_text(text, encoding="utf-8", newline="\n")
    print("wrote %s" % MIME)


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "apple":
        apple(sys.argv[2])
    elif len(sys.argv) in (2, 3) and sys.argv[1] == "linux" and sys.argv[2:] in ([], ["--check"]):
        linux(len(sys.argv) == 3)
    else:
        sys.exit(__doc__)
