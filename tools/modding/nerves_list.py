"""nerves_list.py <Nebula tree> <out.md>: docs/modding/NERVES.md

Every nerve of the game, from its source (NEW_NERVE and NEW_NERVE_ONEND in native/petari): the name a plugin uses
(nerve, set_nerve, hook_nerve), the class whose code runs in it and that code's functions, by class. The names follow
NerveRegistry.cpp's rule: "<class>.<short>", the short name being the nerve's name after "Nrv", else after a leading
"HostType" or the class's own name, else the whole name. The game lists the same names at runtime (nerve_at).
"""
import pathlib
import re
import sys
from collections import defaultdict

NERVE = re.compile(r"^\s*NEW_NERVE(_ONEND)?\(\s*(\w+)\s*,\s*([\w:<>]+)\s*,\s*(\w+)\s*(?:,\s*(\w+)\s*)?\)", re.M)


def short_name(name, cls):
    at = name.find("Nrv")
    if at != -1 and at + 3 < len(name):
        return name[at + 3:]
    if len(name) > 8 and name.startswith("HostType"):
        return name[8:]
    if len(name) > len(cls) and name.startswith(cls):
        return name[len(cls):]
    return name


def main():
    tree, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    root = tree / "native/petari"
    seen = set()
    by_class = defaultdict(list)
    files = defaultdict(set)
    for path in sorted(list((root / "src").rglob("*.cpp")) + list((root / "include").rglob("*.hpp")) +
                       list((root / "include").rglob("*.h"))):
        text = path.read_text(encoding="utf-8", errors="replace")
        if "NEW_NERVE" not in text:
            continue
        for m in NERVE.finditer(text):
            onend, name, cls, exe, end = m.group(1), m.group(2), m.group(3), m.group(4), m.group(5)
            if name == "name":  # the macros themselves
                continue
            if (cls, name) in seen:  # a header's nerve, counted once
                continue
            seen.add((cls, name))
            key = f"{cls}.{short_name(name, cls)}"
            by_class[cls].append((key, f"exe{exe}", f"exe{end}" if onend else ""))
            files[cls].add(path.relative_to(root).as_posix())
    keys = [k for items in by_class.values() for k, _, _ in items]
    dupes = sorted({k for k in keys if keys.count(k) > 1}) if len(keys) != len(set(keys)) else []
    lines = [
        "# Nerves",
        "",
        f"Generated by tools/modding/nerves_list.py from the game's source: {len(keys)} nerves of {len(by_class)} classes.",
        "",
        "The game's objects, screens and the states objects hand their work to run one nerve at a time: Kuribo walks in",
        "`Kuribo.Walk`, and that nerve's code (`exeWalk`) runs every frame until another nerve is set. A plugin:",
        "",
        "- `nerve(actor)`: the name of the nerve an object is in; `nerve_frames(actor)`: its frames in it, from 0.",
        "- `set_nerve(actor, \"Kuribo.Walk\")`: the object goes to another nerve of the same class from its next frame, as",
        "  when the game sets it (its code for entering it runs).",
        "- `hook_nerve(\"Kuribo.Walk\", callback, user)` (in `nebula_plugin_start`): `callback` runs for every object in it,",
        "  with `NEBULA_NERVE_ENTER` as one enters, `NEBULA_NERVE_FRAME` every frame (return 0 and the game's code for",
        "  that frame does not run: the plugin's replaces it) and `NEBULA_NERVE_LEAVE` after the game's own end of it.",
        "- `nerve_at(i)`: the i-th name, for listing them all at runtime.",
        "",
        "A nerve with no hook costs nothing: the game checks one number beside it. Nerves of a state (a class that does an",
        "object's work for a while, such as `WalkerStateWander`) name the state's class; `actor` is the object the state",
        "works for.",
        "",
    ]
    if dupes:
        lines += ["Names shared by two nerves (set_nerve and hook_nerve take the first):", ""]
        lines += [f"- `{k}`" for k in dupes] + [""]
    for cls in sorted(by_class, key=str.lower):
        where = ", ".join(sorted(files[cls]))
        lines += [f"## {cls}", "", f"{where}", "", "| Nerve | Code | On leaving |", "|---|---|---|"]
        for key, exe, end in by_class[cls]:
            lines.append(f"| `{key}` | `{exe}` | {f'`{end}`' if end else ''} |")
        lines.append("")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(keys)} nerves, {len(by_class)} classes, {len(dupes)} shared names -> {out}")


if __name__ == "__main__":
    main()
