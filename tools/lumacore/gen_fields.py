"""The field rows part of gen_lumacore.py: each NameObj class's own fields, from clang's record layouts.

clang -fdump-record-layouts prints every record the classes file lays out (its sizeof rows force each one). Only the
names and types are taken from it; offsets, sizes and types are the compiler's on each platform (LUMACORE_FIELD).
"""
import re

LAYOUT_LINE = re.compile(r'^\s*(\d+(?::\d+-\d+)?)?\s*\|(\s*)(.*)$')
NUMERIC = {'bool', '_Bool', 'signed char', 'unsigned char', 'char', 'short', 'unsigned short', 'int', 'unsigned int',
           'long', 'unsigned long', 'float', 'double', 's8', 'u8', 's16', 'u16', 's32', 'u32', 'f32', 'f64'}
VEC3_TYPES = re.compile(r'^(struct |class )?(JGeometry::)?(TVec3<float>|TVec3<f32>|TVec3f|Vec3f|Vec)$')
HEADER = "// Generated by tools/lumacore/gen_lumacore.py from the game's headers. Do not edit."


def parse_layouts(text):
    """-> {record name: [(field name, type text, is array)]}: each record's own fields, bit-fields left out."""
    out = {}
    for block in text.split('*** Dumping AST Record Layout')[1:]:
        record = None
        base_indent = 0
        for line in block.strip('\n').split('\n'):
            m = LAYOUT_LINE.match(line)
            if m is None:
                continue
            offset, indent, rest = m.group(1), m.group(2), m.group(3).strip()
            if record is None:
                record = re.sub(r'^(class|struct|union)\s+', '', rest)
                base_indent = len(indent)
                if record in out:
                    break
                out[record] = []
                continue
            depth = (len(indent) - base_indent) // 2
            if depth != 1 or offset is None or ':' in offset:
                continue
            if rest.endswith('base)') or 'pointer)' in rest:
                continue
            fm = re.match(r'^(.*?)\s*(\[\d+\](?:\[\d+\])*)?\s+([A-Za-z_]\w*)$', rest)
            if fm is None:
                continue
            out[record].append((fm.group(3), fm.group(1).strip(), fm.group(2) is not None))
    return out


def field_wanted(type_text, row_names):
    t = ' '.join(re.sub(r'\b(const|volatile)\b', ' ', type_text).split())
    if t in NUMERIC or t.startswith('enum '):
        return True
    if VEC3_TYPES.match(t):
        return True
    if t.endswith('*') and not t.endswith('**'):
        target = re.sub(r'^(class|struct)\s+', '', t[:-1].strip())
        return target in row_names or target in ('HitSensor', 'char')
    return False


def emit_field_rows(rows, layouts):
    index = {q: i for i, (q, _, _, _) in enumerate(rows)}
    row_names = set(index)
    headers = sorted({rel for (_, _, rel, _) in rows})
    lines = [HEADER, "// Built with -fno-access-control: the game's own private fields are what mods change.", '',
             '#include "Game/System/LumaCore.hpp"', '#include "Game/System/LumaFieldType.hpp"']
    lines += [f'#include "{h}"' for h in headers]
    lines += ['#include <cstddef>', '', '#pragma clang diagnostic ignored "-Winvalid-offsetof"', '',
              'namespace lumacore {', '    extern const FieldRow kFieldRows[];', '    extern const u32 kFieldRowCount;',
              '    extern const u32 kClassFields[][2];', '    const FieldRow kFieldRows[] = {']
    spans = []
    count = 0
    for q, _, _, _ in rows:
        own = sorted({f for f in layouts.get(q, []) if field_wanted(f[1], row_names)}, key=lambda f: f[0])
        spans.append((count, len(own)))
        for name, _, _ in own:
            lines.append(f'        LUMACORE_FIELD(::{q}, {index[q]}, {name}),')
            count += 1
    if count == 0:
        lines.append('        {0, 0, 0, 0, 0, 0, ""},')
    lines += ['    };', f'    const u32 kFieldRowCount = {count};', '    const u32 kClassFields[][2] = {']
    lines += [f'        {{{a}, {b}}},' for a, b in spans]
    lines += ['    };', '}  // namespace lumacore', '']
    return '\n'.join(lines), count
