// Build tool: the tracer's shaders as MSL. Takes the SPIR-V tools/dev/compile_rt_shaders.py made (rt_shaders_spirv.h,
// linked in) and writes a header of MSL texts, each through runtime/src/render/mtl/shader_msl.cpp's tracer bindings
// (shader_msl.h kRt*), with each shader's threadgroup size (Metal's dispatch names it; MSL does not carry it).
//
//   rt_shaders_msl <output header> macos|ios
//   rt_shaders_msl --files macos|ios <output folder> <module.spv>...   one <name>.metal each (translate_rt_shaders_msl.py)
#include "galaxy/render/mtl/shader_msl.h"

#include "rt_shaders_spirv.h"

#include <cstdio>
#include <cstring>
#include <span>
#include <string>
#include <vector>

using namespace galaxy::render;

namespace {

// The module's LocalSize (OpExecutionMode 16, LocalSize 17); 0s when it has none.
void threads_of(std::span<const std::uint32_t> spirv, std::uint32_t (&threads)[3]) {
    threads[0] = threads[1] = threads[2] = 0u;
    for (std::size_t at = 5u; at < spirv.size();) {
        const std::uint32_t count = spirv[at] >> 16u, op = spirv[at] & 0xFFFFu;
        if (count == 0u || at + count > spirv.size()) {
            return;
        }
        if (op == 16u && count == 6u && spirv[at + 2u] == 17u) {
            threads[0] = spirv[at + 3u];
            threads[1] = spirv[at + 4u];
            threads[2] = spirv[at + 5u];
            return;
        }
        at += count;
    }
}

std::string translate(std::span<const std::uint32_t> spirv, bool ios, std::string& error) {
    mtl::MslOptions options;
    options.ios = ios;
    options.tracer = true;
    return mtl::spirv_to_msl(spirv, mtl::MslStage::Compute, options, error);
}

int files(bool ios, const char* folder, int count, char** paths) {
    int failed = 0;
    for (int i = 0; i < count; ++i) {
        const std::string path = paths[i];
        std::vector<std::uint32_t> spirv;
        if (std::FILE* in = std::fopen(path.c_str(), "rb")) {
            std::uint32_t word = 0u;
            while (std::fread(&word, sizeof(word), 1u, in) == 1u) {
                spirv.push_back(word);
            }
            std::fclose(in);
        }
        const std::size_t slash = path.find_last_of("/\\");
        std::string name = path.substr(slash == std::string::npos ? 0u : slash + 1u);
        name = name.substr(0u, name.find_last_of('.'));
        std::string error;
        const std::string msl = spirv.size() > 5u ? translate(spirv, ios, error) : std::string{};
        if (msl.empty()) {
            std::printf("FAILED %s: %s\n", name.c_str(), spirv.size() > 5u ? error.c_str() : "not a SPIR-V module");
            ++failed;
            continue;
        }
        const std::string target = std::string(folder) + "/" + name + ".metal";
        std::FILE* out = std::fopen(target.c_str(), "wb");
        if (out == nullptr || std::fwrite(msl.data(), 1u, msl.size(), out) != msl.size()) {
            std::printf("FAILED %s: cannot write %s\n", name.c_str(), target.c_str());
            ++failed;
        } else {
            std::uint32_t threads[3];
            threads_of(spirv, threads);
            std::printf("OK %s %u %u %u\n", name.c_str(), threads[0], threads[1], threads[2]);
        }
        if (out != nullptr) {
            std::fclose(out);
        }
    }
    return failed == 0 ? 0 : 1;
}

}  // namespace

int main(int argc, char** argv) {
    if (argc >= 4 && std::strcmp(argv[1], "--files") == 0) {
        return files(std::strcmp(argv[2], "ios") == 0, argv[3], argc - 4, argv + 4);
    }
    if (argc != 3) {
        std::fprintf(stderr, "usage: rt_shaders_msl <output header> macos|ios\n"
                             "       rt_shaders_msl --files macos|ios <output folder> <module.spv>...\n");
        return 2;
    }
    const bool ios = std::strcmp(argv[2], "ios") == 0;
    std::FILE* out = std::fopen(argv[1], "wb");
    if (out == nullptr) {
        return 2;
    }
    std::fprintf(out, "// Generated by platform/apple/tools/rt_shaders_msl.cpp; do not edit.\n#include <cstddef>\n\n");
    constexpr std::size_t kCount = sizeof(kRtShaders) / sizeof(kRtShaders[0]);
    std::uint32_t threads[kCount][3]{};
    bool ok = true;
    for (std::size_t i = 0; i < kCount; ++i) {
        // compile_rt_shaders.py aligns each module to 4 bytes (alignas(4)).
        const std::span<const std::uint32_t> spirv(reinterpret_cast<const std::uint32_t*>(kRtShaders[i].data),
                                                   kRtShaders[i].size / sizeof(std::uint32_t));
        threads_of(spirv, threads[i]);
        std::string error;
        const std::string msl = translate(spirv, ios, error);
        if (msl.empty()) {
            std::fprintf(stderr, "tracer shader %zu: %s\n", i, error.c_str());
            ok = false;
            continue;
        }
        if (msl.find(")NEBULA\"") != std::string::npos) {
            std::fprintf(stderr, "tracer shader %zu: its text holds the header's own delimiter\n", i);
            ok = false;
            continue;
        }
        // In pieces: a compiler's longest string literal is shorter than a long shader.
        std::fprintf(out, "static const char g_rt_msl_%zu[] =", i);
        constexpr std::size_t kPiece = 8192u;
        for (std::size_t at = 0; at < msl.size(); at += kPiece) {
            std::fprintf(out, "\nR\"NEBULA(%s)NEBULA\"", msl.substr(at, kPiece).c_str());
        }
        std::fprintf(out, ";\n");
    }
    // In RtShader's order (shaders.tsv), under the name and fields rt_shaders.cpp reads in the other builds; every
    // entry point is main0 (shader_msl.cpp); size without the closing NUL.
    std::fprintf(out, "\nstatic const struct { const char* data; std::size_t size; unsigned threads[3]; } kRtShaders[] = {\n");
    for (std::size_t i = 0; i < kCount; ++i) {
        std::fprintf(out, "    {g_rt_msl_%zu, sizeof(g_rt_msl_%zu) - 1u, {%uu, %uu, %uu}},\n", i, i, threads[i][0], threads[i][1],
                     threads[i][2]);
    }
    std::fprintf(out, "};\n");
    std::fclose(out);
    if (!ok) {
        std::remove(argv[1]);
    }
    return ok ? 0 : 1;
}
