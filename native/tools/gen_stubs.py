"""gen_stubs.py <boundary.tsv> <implemented.txt> <out .c>: a C-linkage stub for every SDK function in the game
module's boundary (tools/boundary.py) that the native SDK layer does not implement yet (implemented.txt, one name
per line). A stub names itself and stops: the game reaching one is a missing piece, never a silent no-op. Data
symbols, the C library, the C++ runtime and C++-mangled names are left out (they are defined elsewhere)."""
import sys

boundary, implemented_path, out = sys.argv[1:4]
data = {"gxfifo", "__GDCurrentDL", "__DSP_curr_task", "__DSP_first_task", "_current_locale"}
implemented = set()
try:
    implemented = {l.strip() for l in open(implemented_path, encoding="utf-8") if l.strip() and not l.startswith("#")}
except FileNotFoundError:
    pass
names = []
for line in open(boundary, encoding="utf-8").read().splitlines()[1:]:
    sym, _, owner, _ = line.split("\t")
    if sym.startswith("?") or sym in data or sym in implemented:
        continue
    if owner.startswith("sdk:") or owner == "other" or sym.startswith("__DSP_"):
        names.append(sym)
names.sort()
with open(out, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("/* Generated by tools/gen_stubs.py: SDK functions the native layer does not implement yet. */\n")
    fh.write("void nebula_sdk_missing(const char* name);\n\n")
    for n in names:
        fh.write(f'void {n}(void) {{\n    nebula_sdk_missing("{n}");\n}}\n')
print(len(names), "stubs")
